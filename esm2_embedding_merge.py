
"""
esm2_embedding_merge.py

Loads ESM-2 protein language model embeddings (.pt files) and merges them
with influenza metadata to produce a single CSV for downstream model training.

Each .pt file contains per-layer mean representations for one protein sequence.
The script extracts the embedding vector from layer 33, maps it back to the
corresponding metadata row via unique_ID, and outputs a merged CSV.

Usage:
    python esm2_embedding_merge.py \
        --metadata  <path_to_metadata_csv> \
        --embeddings <path_to_embedding_directory> \
        --output     <path_to_output_csv> \
        --layer      33

Inputs:
    - metadata CSV  : Strain-level metadata including unique_ID, Isolate_Name,
                      Host_Family, Classification, Segment, Genotype, etc.
    - embeddings dir: Directory of .pt files generated by ESM-2. Each file is
                      named as 'seq_<index>|<unique_ID>|.pt' and contains a
                      dictionary with 'mean_representations' keyed by layer.
    - layer         : Integer specifying which ESM-2 model layer to extract
                      mean representations from (default: 33).

Outputs:
    - Merged CSV containing metadata columns and ESM-2 embedding features.

Authors: Longest et al., 2026
Date: September 14, 2026
"""

import torch
import numpy as np
import pandas as pd
import random
import os
import argparse


def parse_args():
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Merge ESM-2 embeddings with influenza metadata."
    )
    parser.add_argument(
        "--metadata",
        type=str,
        required=True,
        help="Path to the metadata CSV file containing unique_ID and strain info."
    )
    parser.add_argument(
        "--embeddings",
        type=str,
        required=True,
        help="Path to directory containing ESM-2 .pt embedding files."
    )
    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="Path for the output merged CSV file."
    )
    parser.add_argument(
        "--layer",
        type=int,
        default=33,
        help="ESM-2 layer from which to extract mean representations (default: 33)."
    )
    return parser.parse_args()


def load_metadata(metadata_path):
    """
    Load and deduplicate the metadata CSV.

    Parameters
    ----------
    metadata_path : str
        Path to the metadata CSV file.

    Returns
    -------
    pd.DataFrame
        Deduplicated metadata DataFrame.
    """
    data = pd.read_csv(metadata_path)
    print(f"Total rows before deduplication: {len(data)}")

    data = data.drop_duplicates(subset=["unique_ID"], keep="first")
    print(f"Total rows after deduplication:  {len(data)}")
    print(f"Columns: {data.columns.tolist()}")

    return data


def load_embeddings(embedding_dir, layer):
    """
    Load ESM-2 embedding vectors from .pt files.

    Each .pt file is expected to follow the naming convention:
        seq_<index>|<unique_ID>|.pt

    The unique_ID is extracted from the filename and used to map
    the embedding back to the metadata.

    Parameters
    ----------
    embedding_dir : str
        Path to the directory containing .pt files.
    layer : int
        ESM-2 model layer from which to extract mean representations.

    Returns
    -------
    pd.DataFrame
        DataFrame with embedding features and a unique_ID column.
    """
    embedding_files = [f for f in os.listdir(embedding_dir) if f.endswith(".pt")]
    print(f"\nTotal embedding files found: {len(embedding_files)}")

    # Display a random sample of filenames for verification
    random.seed(42)
    sampled = random.sample(embedding_files, min(10, len(embedding_files)))
    print("\nSample .pt filenames:")
    for sf in sampled:
        print(f"  {sf}")

    embeddings = []
    unique_ids = []
    skipped = 0

    print("\nLoading embedding tensors...")
    for embedding_file in embedding_files:
        # Extract unique_ID from filename pattern: seq_<index>|<unique_ID>|.pt
        filename_no_ext = os.path.splitext(embedding_file)[0]
        parts = filename_no_ext.split("|")

        if len(parts) < 2:
            skipped += 1
            continue

        current_unique_id = parts[1]
        pt_path = os.path.join(embedding_dir, embedding_file)

        # Load the .pt file and extract the specified layer's mean representation
        data_pt = torch.load(pt_path, map_location="cpu")
        embedding_vector = data_pt["mean_representations"][layer].numpy()

        embeddings.append(embedding_vector)
        unique_ids.append(current_unique_id)

    if skipped > 0:
        print(f"Skipped {skipped} files (unexpected naming pattern).")

    embeddings_df = pd.DataFrame(embeddings)
    embeddings_df["unique_ID"] = unique_ids
    print(f"\nEmbeddings DataFrame shape: {embeddings_df.shape}")

    return embeddings_df


def main():
    """Main pipeline: load metadata, load embeddings, merge, and save."""
    args = parse_args()

    # Ensure output directory exists
    output_dir = os.path.dirname(args.output)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    # --- Step 1: Load metadata ---
    print("=" * 60)
    print("Step 1: Loading metadata")
    print("=" * 60)
    metadata = load_metadata(args.metadata)

    # --- Step 2: Load embeddings ---
    print("\n" + "=" * 60)
    print("Step 2: Loading ESM-2 embeddings")
    print("=" * 60)
    embeddings_df = load_embeddings(args.embeddings, args.layer)

    # --- Step 3: Merge ---
    print("\n" + "=" * 60)
    print("Step 3: Merging metadata with embeddings")
    print("=" * 60)
    merged_df = metadata.merge(embeddings_df, on="unique_ID", how="inner")
    print(f"Rows in merged DataFrame: {len(merged_df)}")
    print(f"Columns in merged DataFrame: {len(merged_df.columns)}")

    unmatched = len(metadata) - len(merged_df)
    if unmatched > 0:
        print(f"WARNING: {unmatched} metadata rows had no matching embedding.")

    # --- Step 4: Save ---
    print("\n" + "=" * 60)
    print("Step 4: Saving merged CSV")
    print("=" * 60)
    merged_df.to_csv(args.output, index=False)
    print(f"Output saved to: {args.output}")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    main()

